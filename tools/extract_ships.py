#!/usr/bin/env python3
"""
Extract the ship blueprints from Mark Moxon's annotated 6502 Second Processor
Elite source (https://github.com/markmoxon/elite-source-code-6502-second-processor)
and write them out as a C++ header for the CYD-Elite ESPHome component.

Usage:
    git clone --depth 1 https://github.com/markmoxon/elite-source-code-6502-second-processor.git
    python3 tools/extract_ships.py \
        elite-source-code-6502-second-processor/1-source-files/main-sources/elite-source.asm \
        components/elite_clock/ships.h

Elite was written by Ian Bell and David Braben and is copyright (c) Acornsoft 1985.
The ship geometry is used here for a non-commercial hobby project.
"""
import re
import sys

# Blueprint label -> display name. Order here = order on the clock / in the HA select.
# Pirate variants (identical geometry to the trader versions) are skipped.
SHIPS = [
    ("COBRA_MK_3", "Cobra Mk III"),
    ("PYTHON", "Python"),
    ("VIPER", "Viper"),
    ("SIDEWINDER", "Sidewinder"),
    ("MAMBA", "Mamba"),
    ("KRAIT", "Krait"),
    ("ADDER", "Adder"),
    ("GECKO", "Gecko"),
    ("COBRA_MK_1", "Cobra Mk I"),
    ("WORM", "Worm"),
    ("ASP_MK_2", "Asp Mk II"),
    ("FER_DE_LANCE", "Fer-de-Lance"),
    ("MORAY", "Moray"),
    ("CONSTRICTOR", "Constrictor"),
    ("COUGAR", "Cougar"),
    ("BOA", "Boa"),
    ("ANACONDA", "Anaconda"),
    ("SHUTTLE", "Shuttle"),
    ("TRANSPORTER", "Transporter"),
    ("THARGOID", "Thargoid"),
    ("THARGON", "Thargon"),
    ("CORIOLIS", "Coriolis Station"),
    ("DODO", "Dodo Station"),
    ("MISSILE", "Missile"),
    ("ESCAPE_POD", "Escape Pod"),
    ("CANISTER", "Cargo Canister"),
    ("PLATE", "Alloy Plate"),
    ("ASTEROID", "Asteroid"),
    ("ROCK_HERMIT", "Rock Hermit"),
    ("BOULDER", "Boulder"),
    ("SPLINTER", "Splinter"),
    ("LOGO", "Elite Logo"),
]

VERTEX_RE = re.compile(r"^\s*VERTEX\s+(.+?)\\")
EDGE_RE = re.compile(r"^\s*EDGE\s+(.+?)\\")
FACE_RE = re.compile(r"^\s*FACE\s+(.+?)\\")


def nums(s):
    return [int(x) for x in s.split(",")]


def parse(src):
    lines = src.splitlines()
    labels = {}
    for i, l in enumerate(lines):
        m = re.match(r"^\.SHIP_(\w+)\s*$", l)
        if m:
            labels[m.group(1)] = i

    def block(label, regex):
        """Rows of a VERTEX/EDGE/FACE block starting at .SHIP_<label>"""
        out = []
        i = labels[label] + 1
        while i < len(lines):
            l = lines[i]
            if l.startswith(".") or l.startswith("\\ ****"):
                break
            m = regex.match(l)
            if m:
                out.append(nums(m.group(1)))
            i += 1
        return out

    ships = {}
    for key, _ in SHIPS:
        i = labels[key] + 1
        hdr = {}
        edges_from = key
        while not lines[i].startswith(".SHIP_"):
            l = lines[i]
            m = re.search(r"LO\(SHIP_(\w+)_EDGES - SHIP_\w+\)", l)
            if m:
                edges_from = m.group(1)
            for field, pat in [
                ("edges", r"Number of edges\s*=\s*(\d+)"),
                ("bounty", r"Bounty\s*=\s*(\d+)"),
                ("energy", r"Max\. energy\s*=\s*(\d+)"),
                ("speed", r"Max\. speed\s*=\s*(\d+)"),
                ("laser", r"Laser power\s*=\s*(\d+)"),
                ("missiles", r"Missiles\s*=\s*(\d+)"),
            ]:
                mm = re.search(pat, l)
                if mm and field not in hdr:
                    hdr[field] = int(mm.group(1))
            i += 1
        verts = block(key + "_VERTICES", VERTEX_RE)
        edges = block(edges_from + "_EDGES", EDGE_RE)[: hdr["edges"]]
        faces = block(key + "_FACES", FACE_RE)
        ships[key] = dict(hdr=hdr, verts=verts, edges=edges, faces=faces,
                          borrowed=(edges_from != key))
    return ships


def emit(ships, out):
    w = out.write
    w("// AUTO-GENERATED by tools/extract_ships.py - do not edit by hand.\n")
    w("// Ship blueprints from 6502 Second Processor Elite, via Mark Moxon's\n")
    w("// annotated source at https://elite.bbcelite.com\n")
    w("// Elite (c) Ian Bell & David Braben / Acornsoft 1985.\n\n")
    w("#pragma once\n#include <cstdint>\n\nnamespace esphome {\nnamespace elite_clock {\n\n")
    w("struct ShipVertex { int16_t x, y, z; };\n")
    w("struct ShipEdge { uint8_t v1, v2, f1, f2; };\n")
    w("struct ShipFace { int16_t x, y, z; };\n")
    w("struct ShipBlueprint {\n  const char *name;\n  const ShipVertex *verts; uint8_t num_verts;\n"
      "  const ShipEdge *edges; uint8_t num_edges;\n  const ShipFace *faces; uint8_t num_faces;\n"
      "  bool hidden_lines;   // false when edges/faces don't match (borrowed edges)\n"
      "  uint16_t radius;     // max vertex distance from origin\n"
      "  uint16_t bounty;     // in tenths of a credit\n"
      "  uint8_t energy, speed, laser, missiles;\n};\n\n")
    for key, name in SHIPS:
        s = ships[key]
        k = key.lower()
        w(f"// {name}\n")
        w(f"static const ShipVertex {k}_v[] = {{")
        w(", ".join(f"{{{v[0]},{v[1]},{v[2]}}}" for v in s["verts"]))
        w("};\n")
        w(f"static const ShipEdge {k}_e[] = {{")
        w(", ".join(f"{{{e[0]},{e[1]},{e[2]},{e[3]}}}" for e in s["edges"]))
        w("};\n")
        w(f"static const ShipFace {k}_f[] = {{")
        w(", ".join(f"{{{f[0]},{f[1]},{f[2]}}}" for f in s["faces"]) or "{0,0,0}")
        w("};\n\n")
    w("static const ShipBlueprint SHIPS[] = {\n")
    for key, name in SHIPS:
        s, k, h = ships[key], key.lower(), ships[key]["hdr"]
        r = max(int((v[0] ** 2 + v[1] ** 2 + v[2] ** 2) ** 0.5) for v in s["verts"])
        w(f'  {{"{name}", {k}_v, {len(s["verts"])}, {k}_e, {len(s["edges"])}, {k}_f, {len(s["faces"])}, '
          f'{"false" if s["borrowed"] else "true"}, {r}, {h.get("bounty", 0)}, {h.get("energy", 0)}, '
          f'{h.get("speed", 0)}, {h.get("laser", 0)}, {h.get("missiles", 0)}}},\n')
    w("};\n")
    w(f"static const uint8_t NUM_SHIPS = {len(SHIPS)};\n\n")
    w("}  // namespace elite_clock\n}  // namespace esphome\n")


def main():
    src = open(sys.argv[1], encoding="latin-1").read()
    ships = parse(src)
    for key, name in SHIPS:
        s = ships[key]
        nv = len(s["verts"])
        bad = [e for e in s["edges"] if e[0] >= nv or e[1] >= nv]
        print(f"{name:18s} v={nv:3d} e={len(s['edges']):3d} f={len(s['faces']):3d}"
              f"{' (borrowed edges)' if s['borrowed'] else ''}{' BAD EDGES' if bad else ''}")
    with open(sys.argv[2], "w") as f:
        emit(ships, f)
    # also dump JSON for the preview tool
    if len(sys.argv) > 3:
        import json
        json.dump({n: ships[k] for k, n in SHIPS}, open(sys.argv[3], "w"))


if __name__ == "__main__":
    main()
